async function main() {
  const { db } = await import("../lib/db");
  const { locations, items, locationStock } = await import("../db/schema");
  const { eq, and, or } = await import("drizzle-orm");

  console.log(`Importing ${STOCK_DATA.length} location/SKU stock rows...`);

  let applied = 0;
  const skippedLocations = new Set<string>();
  const skippedSkus = new Set<string>();

  for (const [locCode, sku, qty] of STOCK_DATA) {
    const [location] = await db.select().from(locations).where(eq(locations.code, locCode));
    if (!location) {
      skippedLocations.add(locCode);
      continue;
    }

    const [item] = await db
      .select()
      .from(items)
      .where(or(eq(items.sku, sku), eq(items.legacySku, sku)));
    if (!item) {
      skippedSkus.add(sku);
      continue;
    }

    const [existing] = await db
      .select()
      .from(locationStock)
      .where(and(eq(locationStock.locationId, location.id), eq(locationStock.itemId, item.id)));

    if (existing) {
      await db
        .update(locationStock)
        .set({ quantity: qty, updatedAt: new Date() })
        .where(eq(locationStock.id, existing.id));
    } else {
      await db.insert(locationStock).values({ locationId: location.id, itemId: item.id, quantity: qty });
    }

    applied++;
  }

  console.log(`\nApplied ${applied} of ${STOCK_DATA.length} rows.`);

  if (skippedLocations.size > 0) {
    console.log(`\nSkipped ${skippedLocations.size} unknown location code(s):`);
    console.log([...skippedLocations].join(", "));
  }
  if (skippedSkus.size > 0) {
    console.log(`\nSkipped rows for ${skippedSkus.size} unknown SKU(s):`);
    console.log([...skippedSkus].join(", "));
  }

  process.exit(0);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
